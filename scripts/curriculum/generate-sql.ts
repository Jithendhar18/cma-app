import type { Bundle, RecordStatus, SectionDef } from './types.ts';

/**
 * Turns a VALIDATED bundle into one deterministic SQL file.
 *
 * Properties (each is asserted by tests and by the database integration test):
 *   - Idempotent: running the file twice leaves the database unchanged.
 *   - Non-destructive: it never contains row removal, truncation or object drops. Removal is a status change to
 *     `retired`. It never touches personal tables.
 *   - Stable identity: rows are matched on stable_key, so ids never change.
 *   - Never downgrades: an already published row is not unpublished by a draft entry, and an existing
 *     verification is never replaced by null.
 *   - Safe publishing: the course + syllabus version and attempt availability are inserted as draft and
 *     promoted last, so the database readiness triggers run (and abort the whole import) if the bundle
 *     is incomplete.
 *   - The output depends only on the bundle and its hash. No timestamps, so the same input gives the same bytes.
 */

export interface GenerateOptions {
  /** SHA-256 (hex) of the canonical bundle content, supplied by the caller. */
  contentSha256: string;
  /** Wrap in BEGIN/COMMIT. Tests turn this off so they can roll back. Default true. */
  transaction?: boolean;
  /**
   * Permit an import that would retire EVERY active record in a scope (for example a full re-keying).
   * Without it, the generated SQL aborts (inside its transaction) and names the scope and the count.
   */
  allowRetireAll?: boolean;
}

/** SQL string literal. Single quotes are doubled; control characters are rejected by validation. */
export function lit(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}
const litOrNull = (value: string | null): string => (value === null ? 'null' : lit(value));
const num = (value: number): string => {
  if (!Number.isFinite(value)) throw new Error(`non-finite number in bundle: ${String(value)}`);
  return String(value);
};
const dateOrNull = (value: string | null): string => (value === null ? 'null' : `${lit(value)}::date`);
const stamp = (value: string | null): string => (value === null ? 'null' : `${lit(`${value} 00:00:00+00`)}::timestamptz`);
const bool = (value: boolean): string => (value ? 'true' : 'false');
/** Sorted, so the same content always produces the same bytes whatever order the JSON lists it in. */
const textArray = (values: string[]): string => `array[${[...values].sort().map(lit).join(', ')}]::text[]`;

const source = (ref: string | null): string =>
  ref === null ? 'null' : `(select id from public.source_references where stable_key = ${lit(ref)})`;

/** Keeps an existing published/retired state unless the bundle explicitly publishes. */
const keepStatus = (table: string): string =>
  `status = case when excluded.status = 'published' then 'published' else public.${table}.status end`;
/** Never replaces a recorded verification with null. */
const keepVerification = (table: string): string =>
  `verified_at = coalesce(excluded.verified_at, public.${table}.verified_at), ` +
  `verified_by = coalesce(excluded.verified_by, public.${table}.verified_by), ` +
  `source_reference_id = coalesce(excluded.source_reference_id, public.${table}.source_reference_id)`;

const csvId = (bundleKey: string): string =>
  `(select id from public.course_syllabus_versions where stable_key = ${lit(bundleKey)})`;

function depthOf(section: SectionDef, byKey: Map<string, SectionDef>): number {
  let depth = 0;
  let cursor = section.parent;
  while (cursor !== null) {
    depth += 1;
    cursor = byKey.get(cursor)?.parent ?? null;
  }
  return depth;
}

export function generateSql(bundle: Bundle, options: GenerateOptions): string {
  if (!/^[0-9a-f]{64}$/.test(options.contentSha256)) throw new Error('contentSha256 must be a 64 character hex digest');
  const transaction = options.transaction ?? true;
  const allowRetireAll = options.allowRetireAll ?? false;
  const m = bundle.meta;
  const csv = csvId(m.bundleKey);
  const out: string[] = [];
  const add = (...lines: string[]) => out.push(...lines);
  const section = (title: string) => add('', `-- ${title}`);

  add(
    `-- GENERATED by scripts/curriculum/generate-sql.ts. Do not edit by hand.`,
    `-- bundle: ${m.bundleKey}  version: ${m.bundleVersion}`,
    `-- content sha256: ${options.contentSha256}`,
    `-- This file only inserts, updates and retires curriculum rows, and never touches student data.`,
  );
  if (transaction) add('begin;');

  // 0. retire-all guard. Evaluated BEFORE any upsert, so it sees only what existed before this import.
  //    If every active record in a scope would be retired, abort (or, with --allow-retire-all, announce it).
  section(allowRetireAll
    ? 'retire-all guard: OVERRIDDEN with --allow-retire-all (scope and count are announced below)'
    : 'retire-all guard: aborts if this import would retire every active record in a scope');
  const scopes: Array<[label: string, table: string, keys: string[]]> = [
    ['subject groups', 'subject_groups', bundle.groups.map((g) => g.stableKey)],
    ['subjects', 'subjects', bundle.subjects.map((s) => s.stableKey)],
    ['sections', 'syllabus_sections', bundle.sections.map((s) => s.stableKey)],
    ['chapters', 'chapters', bundle.chapters.map((c) => c.stableKey)],
    ['weightages', 'official_weightages', bundle.weightages.map((w) => w.stableKey)],
    ['resources', 'study_resources', bundle.resources.map((r) => r.stableKey)],
  ];
  add('do $guard$', 'declare', `  scope_csv uuid := ${csv};`, '  prior int;', '  retiring int;', 'begin');
  for (const [label, table, keys] of scopes) {
    add(
      `  select count(*) into prior from public.${table} where csv_id = scope_csv and status <> 'retired';`,
      `  select count(*) into retiring from public.${table} where csv_id = scope_csv and status <> 'retired' and stable_key::text <> all (${textArray(keys)});`,
      `  if prior > 0 and retiring = prior then`,
      allowRetireAll
        ? `    raise notice 'retire-all ALLOWED: this import retires all % active record(s) in scope "${label}" of ${m.bundleKey}', retiring;`
        : `    raise exception 'import would retire ALL % active record(s) in scope "${label}" of ${m.bundleKey}; nothing was changed. Re-run with --allow-retire-all to confirm.', retiring using errcode = '23514';`,
      `  end if;`,
    );
  }
  add('end', '$guard$;');

  // 1. sources -----------------------------------------------------------------------------------------------
  section('sources');
  for (const s of [...bundle.sources].sort((a, b) => a.stableKey.localeCompare(b.stableKey))) {
    add(
      `insert into public.source_references (stable_key, title, url, document_type, published_on, retrieved_on, note)`,
      `values (${lit(s.stableKey)}, ${lit(s.title)}, ${litOrNull(s.url)}, ${lit(s.documentType)}, ${dateOrNull(s.publishedOn)}, ${dateOrNull(s.retrievedOn)}, ${litOrNull(s.note)})`,
      `on conflict (stable_key) do update set title = excluded.title, url = excluded.url, document_type = excluded.document_type,`,
      `  published_on = excluded.published_on, retrieved_on = excluded.retrieved_on, note = excluded.note;`,
    );
  }

  // 2. course, syllabus version, and their scope (CSV, inserted as draft) -------------------------------------------
  section('course');
  add(
    `insert into public.courses (stable_key, name, level_order, status, verified_at, verified_by, source_reference_id)`,
    `values (${lit(m.course.stableKey)}, ${lit(m.course.name)}, ${num(m.course.levelOrder)}, ${lit(m.course.status)}, ${stamp(m.course.verifiedAt)}, ${litOrNull(m.course.verifiedBy)}, ${source(m.course.sourceRef)})`,
    `on conflict (stable_key) do update set name = excluded.name, level_order = excluded.level_order,`,
    `  ${keepStatus('courses')}, ${keepVerification('courses')};`,
  );
  section('syllabus version');
  add(
    `insert into public.syllabus_versions (stable_key, name, effective_from, status, verified_at, verified_by, source_reference_id)`,
    `values (${lit(m.syllabus.stableKey)}, ${lit(m.syllabus.name)}, ${dateOrNull(m.syllabus.effectiveFrom)}, ${lit(m.syllabus.status)}, ${stamp(m.syllabus.verifiedAt)}, ${litOrNull(m.syllabus.verifiedBy)}, ${source(m.syllabus.sourceRef)})`,
    `on conflict (stable_key) do update set name = excluded.name, effective_from = excluded.effective_from,`,
    `  ${keepStatus('syllabus_versions')}, ${keepVerification('syllabus_versions')};`,
  );
  section('course + syllabus version (CSV): draft now, promoted last');
  add(
    `insert into public.course_syllabus_versions (stable_key, course_id, syllabus_version_id, status, verified_at, verified_by, source_reference_id)`,
    `select ${lit(m.bundleKey)}, c.id, s.id, 'draft', ${stamp(m.courseSyllabus.verifiedAt)}, ${litOrNull(m.courseSyllabus.verifiedBy)}, ${source(m.courseSyllabus.sourceRef)}`,
    `  from public.courses c, public.syllabus_versions s`,
    ` where c.stable_key = ${lit(m.course.stableKey)} and s.stable_key = ${lit(m.syllabus.stableKey)}`,
    `on conflict (stable_key) do update set ${keepVerification('course_syllabus_versions')};`,
  );

  // 3. attempts (shared across bundles) ------------------------------------------------------------------------------
  section('exam attempts');
  for (const a of [...bundle.attempts].sort((x, y) => x.stableKey.localeCompare(y.stableKey))) {
    add(
      `insert into public.exam_attempts (stable_key, year, session, label, exam_start_date, exam_end_date, date_status, status, verified_at, verified_by, source_reference_id)`,
      `values (${lit(a.stableKey)}, ${num(a.year)}, ${lit(a.session)}, ${lit(a.label)}, ${dateOrNull(a.examStartDate)}, ${dateOrNull(a.examEndDate)}, ${lit(a.dateStatus)}, ${lit(a.status)}, ${stamp(a.verifiedAt)}, ${litOrNull(a.verifiedBy)}, ${source(a.sourceRef)})`,
      `on conflict (stable_key) do update set label = excluded.label, exam_start_date = excluded.exam_start_date,`,
      `  exam_end_date = excluded.exam_end_date, date_status = excluded.date_status, ${keepStatus('exam_attempts')}, ${keepVerification('exam_attempts')};`,
    );
  }

  // 4. groups --------------------------------------------------------------------------------------------------------
  section('subject groups');
  for (const g of [...bundle.groups].sort((a, b) => a.sortOrder - b.sortOrder)) {
    add(
      `insert into public.subject_groups (csv_id, stable_key, name, sort_order, status, verified_at, verified_by, source_reference_id)`,
      `select csv.id, ${lit(g.stableKey)}, ${lit(g.name)}, ${num(g.sortOrder)}, ${lit(g.status)}, ${stamp(g.verifiedAt)}, ${litOrNull(g.verifiedBy)}, ${source(g.sourceRef)}`,
      `  from public.course_syllabus_versions csv where csv.stable_key = ${lit(m.bundleKey)}`,
      `on conflict (csv_id, stable_key) do update set name = excluded.name, sort_order = excluded.sort_order,`,
      `  ${keepStatus('subject_groups')}, ${keepVerification('subject_groups')};`,
    );
  }

  // 5. subjects ------------------------------------------------------------------------------------------------------
  section('subjects');
  for (const s of [...bundle.subjects].sort((a, b) => a.paperNumber - b.paperNumber)) {
    add(
      `insert into public.subjects (csv_id, subject_group_id, stable_key, slug, paper_number, name, short_name, sort_order, status, verified_at, verified_by, source_reference_id)`,
      `select csv.id, (select g.id from public.subject_groups g where g.csv_id = csv.id and g.stable_key = ${lit(s.group)}),`,
      `       ${lit(s.stableKey)}, ${lit(s.slug)}, ${num(s.paperNumber)}, ${lit(s.name)}, ${lit(s.shortName)}, ${num(s.sortOrder)}, ${lit(s.status)}, ${stamp(s.verifiedAt)}, ${litOrNull(s.verifiedBy)}, ${source(s.sourceRef)}`,
      `  from public.course_syllabus_versions csv where csv.stable_key = ${lit(m.bundleKey)}`,
      `on conflict (csv_id, stable_key) do update set subject_group_id = excluded.subject_group_id, slug = excluded.slug,`,
      `  paper_number = excluded.paper_number, name = excluded.name, short_name = excluded.short_name, sort_order = excluded.sort_order,`,
      `  ${keepStatus('subjects')}, ${keepVerification('subjects')};`,
    );
  }

  // 6. sections, parents before children -------------------------------------------------------------------------------
  section('syllabus sections');
  const sectionByKey = new Map(bundle.sections.map((s) => [s.stableKey, s]));
  const orderedSections = [...bundle.sections].sort(
    (a, b) => depthOf(a, sectionByKey) - depthOf(b, sectionByKey) || a.subject.localeCompare(b.subject) || a.sortOrder - b.sortOrder,
  );
  for (const s of orderedSections) {
    add(
      `insert into public.syllabus_sections (csv_id, subject_id, parent_section_id, stable_key, official_label, title, sort_order, status, verified_at, verified_by, source_reference_id)`,
      `select csv.id, (select x.id from public.subjects x where x.csv_id = csv.id and x.stable_key = ${lit(s.subject)}),`,
      `       ${s.parent === null ? 'null' : `(select p.id from public.syllabus_sections p where p.csv_id = csv.id and p.stable_key = ${lit(s.parent)})`},`,
      `       ${lit(s.stableKey)}, ${litOrNull(s.officialLabel)}, ${lit(s.title)}, ${num(s.sortOrder)}, ${lit(s.status)}, ${stamp(s.verifiedAt)}, ${litOrNull(s.verifiedBy)}, ${source(s.sourceRef)}`,
      `  from public.course_syllabus_versions csv where csv.stable_key = ${lit(m.bundleKey)}`,
      `on conflict (csv_id, stable_key) do update set subject_id = excluded.subject_id, parent_section_id = excluded.parent_section_id,`,
      `  official_label = excluded.official_label, title = excluded.title, sort_order = excluded.sort_order,`,
      `  ${keepStatus('syllabus_sections')}, ${keepVerification('syllabus_sections')};`,
    );
  }

  // 7. chapters ----------------------------------------------------------------------------------------------------------
  section('chapters');
  const orderedChapters = [...bundle.chapters].sort((a, b) => a.subject.localeCompare(b.subject) || a.sequenceNo - b.sequenceNo);
  for (const c of orderedChapters) {
    add(
      `insert into public.chapters (csv_id, subject_id, section_id, stable_key, official_label, title, sequence_no, suggested_study_hours, status, verified_at, verified_by, source_reference_id)`,
      `select csv.id, (select x.id from public.subjects x where x.csv_id = csv.id and x.stable_key = ${lit(c.subject)}),`,
      `       ${c.section === null ? 'null' : `(select p.id from public.syllabus_sections p where p.csv_id = csv.id and p.stable_key = ${lit(c.section)})`},`,
      `       ${lit(c.stableKey)}, ${litOrNull(c.officialLabel)}, ${lit(c.title)}, ${num(c.sequenceNo)}, ${c.suggestedStudyHours === null ? 'null' : num(c.suggestedStudyHours)}, ${lit(c.status)}, ${stamp(c.verifiedAt)}, ${litOrNull(c.verifiedBy)}, ${source(c.sourceRef)}`,
      `  from public.course_syllabus_versions csv where csv.stable_key = ${lit(m.bundleKey)}`,
      `on conflict (csv_id, stable_key) do update set subject_id = excluded.subject_id, section_id = excluded.section_id,`,
      `  official_label = excluded.official_label, title = excluded.title, sequence_no = excluded.sequence_no,`,
      `  suggested_study_hours = excluded.suggested_study_hours, ${keepStatus('chapters')}, ${keepVerification('chapters')};`,
    );
  }
  for (const c of orderedChapters.filter((x) => x.supersededBy !== null)) {
    add(
      `update public.chapters set superseded_by_chapter_id =`,
      `  (select n.id from public.chapters n where n.csv_id = ${csv} and n.stable_key = ${lit(c.supersededBy as string)})`,
      ` where csv_id = ${csv} and stable_key = ${lit(c.stableKey)};`,
    );
  }

  // 8. weightages (exactly as published; never derived) --------------------------------------------------------------------
  section('official weightages (stored at the level they were published; never derived)');
  for (const w of [...bundle.weightages].sort((a, b) => a.stableKey.localeCompare(b.stableKey))) {
    const column = w.level === 'subject' ? 'subject_id' : w.level === 'section' ? 'section_id' : 'chapter_id';
    const lookupTable = w.level === 'subject' ? 'subjects' : w.level === 'section' ? 'syllabus_sections' : 'chapters';
    const lookup = `(select t.id from public.${lookupTable} t where t.csv_id = csv.id and t.stable_key = ${lit(w.target)})`;
    add(
      `insert into public.official_weightages (csv_id, stable_key, level, ${column}, min_percent, max_percent, published_label, status, verified_at, verified_by, source_reference_id)`,
      `select csv.id, ${lit(w.stableKey)}, ${lit(w.level)}, ${lookup}, ${num(w.minPercent)}, ${num(w.maxPercent)}, ${lit(w.publishedLabel)}, ${lit(w.status)}, ${stamp(w.verifiedAt)}, ${litOrNull(w.verifiedBy)}, ${source(w.sourceRef)}`,
      `  from public.course_syllabus_versions csv where csv.stable_key = ${lit(m.bundleKey)}`,
      `on conflict (csv_id, stable_key) do update set min_percent = excluded.min_percent, max_percent = excluded.max_percent,`,
      `  published_label = excluded.published_label, ${keepStatus('official_weightages')}, ${keepVerification('official_weightages')};`,
    );
  }

  // 9. resources (metadata and official links only) -----------------------------------------------------------------------
  section('study resources (links and metadata only)');
  for (const r of [...bundle.resources].sort((a, b) => a.stableKey.localeCompare(b.stableKey))) {
    const subj = r.scope.subject === null ? 'null' : `(select t.id from public.subjects t where t.csv_id = csv.id and t.stable_key = ${lit(r.scope.subject)})`;
    const chap = r.scope.chapter === null ? 'null' : `(select t.id from public.chapters t where t.csv_id = csv.id and t.stable_key = ${lit(r.scope.chapter)})`;
    const att = r.scope.attempt === null ? 'null' : `(select t.id from public.exam_attempts t where t.stable_key = ${lit(r.scope.attempt)})`;
    add(
      `insert into public.study_resources (stable_key, resource_type, title, url, publisher, is_official, csv_id, subject_id, chapter_id, exam_attempt_id, year, session, link_status, last_checked_at, status, verified_at, verified_by, source_reference_id)`,
      `select ${lit(r.stableKey)}, ${lit(r.resourceType)}, ${lit(r.title)}, ${lit(r.url)}, ${lit(r.publisher)}, ${bool(r.isOfficial)}, csv.id, ${subj}, ${chap}, ${att}, ${r.year === null ? 'null' : num(r.year)}, ${litOrNull(r.session)}, ${lit(r.linkStatus)}, ${stamp(r.lastCheckedAt)}, ${lit(r.status)}, ${stamp(r.verifiedAt)}, ${litOrNull(r.verifiedBy)}, ${source(r.sourceRef)}`,
      `  from public.course_syllabus_versions csv where csv.stable_key = ${lit(m.bundleKey)}`,
      `on conflict (stable_key) do update set title = excluded.title, url = excluded.url, publisher = excluded.publisher,`,
      `  is_official = excluded.is_official, subject_id = excluded.subject_id, chapter_id = excluded.chapter_id, exam_attempt_id = excluded.exam_attempt_id,`,
      `  year = excluded.year, session = excluded.session, link_status = excluded.link_status, last_checked_at = excluded.last_checked_at,`,
      `  ${keepStatus('study_resources')}, ${keepVerification('study_resources')};`,
    );
  }

  // 10. retire what this bundle no longer lists (never delete) ---------------------------------------------------------------
  section('retire rows this bundle no longer lists (a status change; nothing is removed)');
  const retire = (table: string, keys: string[]) =>
    add(
      `update public.${table} set status = 'retired'`,
      ` where csv_id = ${csv} and status <> 'retired' and stable_key::text <> all (${textArray(keys)});`,
    );
  retire('subject_groups', bundle.groups.map((g) => g.stableKey));
  retire('subjects', bundle.subjects.map((s) => s.stableKey));
  retire('syllabus_sections', bundle.sections.map((s) => s.stableKey));
  retire('chapters', bundle.chapters.map((c) => c.stableKey));
  retire('official_weightages', bundle.weightages.map((w) => w.stableKey));
  retire('study_resources', bundle.resources.map((r) => r.stableKey));

  // 11. availability: upsert as draft, promote last ---------------------------------------------------------------------------
  section('attempt availability (draft first)');
  for (const a of [...bundle.availability].sort((x, y) => x.attempt.localeCompare(y.attempt))) {
    add(
      `insert into public.course_attempt_availability (csv_id, exam_attempt_id, status, verified_at, verified_by, source_reference_id)`,
      `select csv.id, e.id, 'draft', ${stamp(a.verifiedAt)}, ${litOrNull(a.verifiedBy)}, ${source(a.sourceRef)}`,
      `  from public.course_syllabus_versions csv, public.exam_attempts e`,
      ` where csv.stable_key = ${lit(m.bundleKey)} and e.stable_key = ${lit(a.attempt)}`,
      `on conflict (csv_id, exam_attempt_id) do update set ${keepVerification('course_attempt_availability')};`,
    );
  }
  add(
    `update public.course_attempt_availability set status = 'disabled'`,
    ` where csv_id = ${csv} and status = 'enabled'`,
    `   and exam_attempt_id not in (select id from public.exam_attempts where stable_key::text = any (${textArray(bundle.availability.map((a) => a.attempt))}));`,
  );

  // 12. promote: the database readiness triggers run here and abort the whole import if the bundle is incomplete --------------
  section('promote (readiness is enforced by the database; an incomplete bundle aborts here)');
  const promoteStatus: RecordStatus = m.courseSyllabus.status;
  if (promoteStatus === 'published') {
    add(
      `update public.course_syllabus_versions set status = 'published'`,
      ` where stable_key = ${lit(m.bundleKey)} and status <> 'published';`,
    );
  }
  for (const a of bundle.availability) {
    if (a.status === 'draft') continue;
    add(
      `update public.course_attempt_availability set status = ${lit(a.status)}`,
      ` where csv_id = ${csv} and exam_attempt_id = (select id from public.exam_attempts where stable_key = ${lit(a.attempt)})`,
      `   and status <> ${lit(a.status)};`,
    );
  }

  // 13. audit record, written only if everything above succeeded ----------------------------------------------------------------
  section('audit');
  const summary = {
    sources: bundle.sources.length, attempts: bundle.attempts.length, groups: bundle.groups.length,
    subjects: bundle.subjects.length, sections: bundle.sections.length, chapters: bundle.chapters.length,
    weightages: bundle.weightages.length, resources: bundle.resources.length,
  };
  add(
    `insert into public.curriculum_import_batches (bundle_key, bundle_version, content_sha256, summary)`,
    `values (${lit(m.bundleKey)}, ${lit(m.bundleVersion)}, ${lit(options.contentSha256)}, ${lit(JSON.stringify(summary))}::jsonb)`,
    `on conflict (bundle_key, content_sha256) do nothing;`,
  );

  if (transaction) add('commit;');
  return `${out.join('\n')}\n`;
}

/** Personal (student) tables. A curriculum import must never reference any of them. */
export const PERSONAL_TABLES = [
  'profiles', 'user_settings', 'student_enrollments', 'enrollment_groups', 'chapter_progress',
  'planner_sessions', 'study_sessions', 'revisions', 'practice_records', 'mock_tests', 'local_import_runs',
] as const;

export interface SafetyIssue {
  rule: string;
  excerpt: string;
}

/**
 * Scans SQL (outside string literals) for anything an import must never contain. Run on every generated
 * file, locally and in CI.
 */
export function findUnsafeSql(sql: string): SafetyIssue[] {
  const code = sql.replace(/'(?:[^']|'')*'/g, "''").replace(/--[^\n]*/g, '');
  const issues: SafetyIssue[] = [];
  const rules: Array<[string, RegExp]> = [
    ['no DELETE', /\bdelete\s+from\b/i],
    ['no TRUNCATE', /\btruncate\b/i],
    ['no DROP', /\bdrop\s+(table|schema|trigger|function|constraint|index|type|domain|policy|view|extension|column)\b/i],
    ['no ALTER TABLE', /\balter\s+(table|schema|policy|function)\b/i],
    ['no GRANT or REVOKE', /\b(grant|revoke)\b/i],
    ['no RLS changes', /\b(enable|disable|force)\s+row\s+level\s+security\b/i],
    ['no auth schema access', /\bauth\./i],
    ['no CREATE statements', /\bcreate\s+(table|schema|function|trigger|policy|role|extension)\b/i],
  ];
  for (const [rule, pattern] of rules) {
    const match = pattern.exec(code);
    if (match) issues.push({ rule, excerpt: match[0] });
  }
  for (const table of PERSONAL_TABLES) {
    const pattern = new RegExp(`\\b(public\\.)?${table}\\b`, 'i');
    const match = pattern.exec(code);
    if (match) issues.push({ rule: `must not reference personal table ${table}`, excerpt: match[0] });
  }
  return issues;
}
